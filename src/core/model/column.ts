export function getColumn(iCol: number): Readonly<Column> {
  const def = defaultColumns[iCol < niB ? iCol : niB];
  if (def === undefined) throw new RangeError(`No column ${iCol}`);
  return def;
}

export function isColumnNumeric(iCol: number): boolean {
  return getColumn(iCol).isNumeric;
}

export function isColumnSound(iCol: number): boolean {
  return getColumn(iCol).isSound;
}

export function isColumnImage(iCol: number): boolean {
  return getColumn(iCol).isImage;
}
