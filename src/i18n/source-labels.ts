import { stripMnemonic, type Lang } from './lang.ts';

export interface LocaleContext {
  readonly lang: Lang | undefined;
  readonly english: Lang | undefined;
}

export function sourceLabel(
  locale: LocaleContext | undefined,
  path: string,
  fallback: string,
): string {
  const english = locale?.english?.menu(path, fallback) ?? fallback;
  return stripMnemonic(locale?.lang?.menu(path, english) ?? english);
}

