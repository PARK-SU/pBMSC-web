export function featureText(
  file: LangFile | undefined,
  text: string,
  locale?: LocaleContext,
): string {
  const fallback = file === 'kor.Lang.xml' ? (korean[text] ?? text) : text;
  const path = featureLabelPaths[text];
  return path && locale ? sourceLabel(locale, path, fallback) : fallback;
}

export function featureMessage(file: LangFile | undefined, text: string): string {
  if (file !== 'kor.Lang.xml') return text;
  const files = /^(\d+) files · ([\s\S]*)$/.exec(text);
  if (files) return `${files[1]}개 파일 · ${files[2]}`;
  const minimum = /^Please enter a value that is greater than (.+)\.$/.exec(text);
  if (minimum) return `${minimum[1]}보다 큰 값을 입력하세요.`;
  const colon = text.lastIndexOf(': ');
  if (colon >= 0) {
    const detail = text.slice(colon + 2),
      translated = featureText(file, detail);
    if (translated !== detail) return `${text.slice(0, colon)}: ${translated}`;
  }
  for (const prefix of [
    'Duplicate ZIP path',
    'Duplicate project path',
    'Absolute project path',
    'Path leaves the project',
    'Chart not found',
  ])
    if (text.startsWith(prefix + ': '))
      return featureText(file, prefix) + text.slice(prefix.length);
  return featureText(file, text);
}
